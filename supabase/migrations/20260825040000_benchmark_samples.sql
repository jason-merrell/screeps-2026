create table if not exists public.benchmark_samples (
  id bigint generated by default as identity primary key,
  sample_key text not null unique,
  colony_id uuid references public.colonies(id) on delete set null,
  benchmark_name text not null,
  runtime_sha text,
  captured_at timestamptz,
  metrics jsonb not null check (jsonb_typeof(metrics) = 'object'),
  source text not null,
  source_ref text,
  inserted_at timestamptz not null default now()
);

create index if not exists benchmark_samples_inserted_idx
  on public.benchmark_samples (inserted_at desc);

alter table public.benchmark_samples enable row level security;

create policy "public benchmark samples are readable"
  on public.benchmark_samples
  for select
  to anon, authenticated
  using (true);

